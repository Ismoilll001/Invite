function CornerBranch({layout,animate}:{layout:Arrangement;animate:boolean}){
 const id=useId();
 const artwork=useRef<SVGSVGElement>(null);
 useRoseGrowth(artwork);
 return <svg ref={artwork} className={`rose-flourish rose-cover-florals rose-cover-${layout.position}`} viewBox="0 0 400 320"
  aria-hidden="true" focusable="false" data-blooming={animate ? "" : undefined}>
  <RoseMetalDefs id={id}/>
  <g className="rose-sway" style={{transformOrigin:layout.root}}>
   <g style={{"--rose-foil":`url(#${id}-stem)`} as CSSProperties}>
    <path className="rose-flourish-stem" pathLength="1" d={layout.stem}/>
    {layout.twigs.map((path,index)=><path key={path} className="rose-flourish-stem rose-flourish-twig" pathLength="1"
     style={{animationDelay:`var(--rose-local-start, calc(var(--rose-twig-start) + ${index} * var(--rose-twig-step)))`}} d={path}/>)}
   </g>
   {layout.leaves.map((leaf,index)=><LeafFoil key={index} leaf={[leaf[0],leaf[1],leaf[2],leaf[3]*.57]} id={id} index={index}/>)}
   {layout.flowers.map((flower,index)=><RoseFoil key={index} flower={[flower[0],flower[1],flower[2]*.56,flower[3]]} id={id} index={index}/>)}
  </g>
 </svg>;
}

